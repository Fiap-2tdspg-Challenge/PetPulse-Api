-- Sprint 4: integração com o motor de IA (PetPulse-AI)

-- Temperatura corporal enviada pela coleira (DS18B20), usada pela IA na detecção de febre.
ALTER TABLE T_CLY_LEITURA_IOT ADD (TEMPERATURA NUMBER(5,2));

ALTER TABLE T_CLY_LEITURA_IOT ADD CONSTRAINT CK_CLY_LEITURA_TEMP
    CHECK (TEMPERATURA IS NULL OR (TEMPERATURA >= 30 AND TEMPERATURA <= 45));

-- Nova origem para os alertas gerados pelo motor de IA.
ALTER TABLE T_CLY_ALERTA_INTELIGENTE DROP CONSTRAINT CK_CLY_ALERTA_ORIGEM;

ALTER TABLE T_CLY_ALERTA_INTELIGENTE ADD CONSTRAINT CK_CLY_ALERTA_ORIGEM
    CHECK (ORIGEM_ALERTA IN ('HISTORICO_CLINICO', 'DISPOSITIVO_IOT', 'SISTEMA', 'USUARIO', 'MOTOR_IA'));

-- Tipos de alerta que a IA pode devolver além dos já existentes
-- (FREQUENCIA_CARDIACA, PRESSAO e ATIVIDADE já foram carregados na V3).
INSERT INTO T_CLY_TIPO_ALERTA (DESCRICAO)
SELECT 'TEMPERATURA' FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM T_CLY_TIPO_ALERTA WHERE DESCRICAO = 'TEMPERATURA');

INSERT INTO T_CLY_TIPO_ALERTA (DESCRICAO)
SELECT 'ANOMALIA_MULTIVARIADA' FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM T_CLY_TIPO_ALERTA WHERE DESCRICAO = 'ANOMALIA_MULTIVARIADA');
